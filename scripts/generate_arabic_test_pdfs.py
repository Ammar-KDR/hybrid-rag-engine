def main():
    generated_pdfs = []
    for doc in DOCS:
        pdf_path = RAW_DIR / doc["filename"]
        html_path = TEMP_DIR / f"{Path(doc['filename']).stem}.html"

        html_content = create_html(doc)
        html_path.write_text(html_content, encoding="utf-8")

        # Convert to PDF via headless Microsoft Edge
        cmd = [
            EDGE_PATH,
            "--headless",
            "--disable-gpu",
            f"--print-to-pdf={pdf_path}",
            f"file:///{html_path.as_posix()}",
        ]
        res = subprocess.run(cmd, capture_output=True, text=True)
        if pdf_path.exists():
            print(f"Generated: {pdf_path.name} ({pdf_path.stat().st_size} bytes)")
            generated_pdfs.append(pdf_path)
        else:
            print(f"Failed to generate: {doc['filename']}, return code: {res.returncode}")

    print(f"\nSuccessfully generated {len(generated_pdfs)} official Arabic PDF documents.")


if __name__ == "__main__":
    main()
